#!/usr/bin/env python3
"""Build a Gazebo world and map_server maps from a floor plan layout YAML.

Input: the layout written by trace_floorplan.py (free-space polygon with obstacle
holes, keep-out rectangles, door goals; meters, map frame == world frame).
Outputs, all from the same polygons so the Gazebo LiDAR and the 2D raycaster see
the same walls:
  WORLD.sdf               one static model: a thin wall box along every polygon edge
  MAP.pgm/.yaml           occupancy map (free inside the polygon, walls around it)
  MAP_keepout.pgm/.yaml   Nav2 keepout-filter mask: the keep-out zones as occupied

Usage: build_floorplan_world.py LAYOUT_YAML WORLD_SDF MAP_YAML
"""
import argparse
import math
import os

import cv2

import numpy as np

import yaml

RESOLUTION = 0.05
MAP_MARGIN = 1.0  # m of map around the free space
WALL_THICKNESS = 0.05  # thin: some traced walls (stubs between door pockets) are 1 cell
WALL_HEIGHT = 2.5
WALL_BAND = 0.25  # m of occupied cells drawn outside the free space; the rest is unknown

WORLD_HEADER = """<?xml version="1.0"?>
<!-- Generated by src/cash_sim/tools/build_floorplan_world.py from {layout}. Do not edit:
     change the layout (or the tracer) and regenerate. {description} -->
<sdf version="1.9">
  <world name="{world}">
    <physics name="1ms" type="ignored">
      <max_step_size>0.001</max_step_size>
      <real_time_factor>1.0</real_time_factor>
    </physics>

    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors">
      <render_engine>ogre2</render_engine>
    </plugin>

    <scene>
      <ambient>0.5 0.5 0.5 1</ambient>
      <background>0.8 0.8 0.8 1</background>
      <shadows>false</shadows>
    </scene>

    <light type="directional" name="sun">
      <cast_shadows>false</cast_shadows>
      <pose>0 0 10 0 0 0</pose>
      <diffuse>0.9 0.9 0.9 1</diffuse>
      <specular>0.2 0.2 0.2 1</specular>
      <direction>-0.3 0.2 -0.9</direction>
    </light>

    <model name="floor">
      <static>true</static>
      <pose>{cx:.3f} {cy:.3f} 0 0 0 0</pose>
      <link name="link">
        <collision name="collision">
          <geometry><plane><normal>0 0 1</normal><size>{sx:.1f} {sy:.1f}</size></plane></geometry>
        </collision>
        <visual name="visual">
          <geometry><plane><normal>0 0 1</normal><size>{sx:.1f} {sy:.1f}</size></plane></geometry>
          <material>
            <ambient>0.55 0.55 0.55 1</ambient><diffuse>0.55 0.55 0.55 1</diffuse>
          </material>
        </visual>
      </link>
    </model>

    <model name="walls">
      <static>true</static>
      <link name="link">
"""
BOX = ('<pose>{x:.3f} {y:.3f} {z:.3f} 0 0 {yaw:.4f}</pose>'
       '<geometry><box><size>{length:.3f} {t:.3f} {h:.3f}</size></box></geometry>')
WALL = ('        <collision name="c{i}">' + BOX + '</collision>\n'
        '        <visual name="v{i}">' + BOX + '<material><ambient>0.85 0.85 0.80 1</ambient>'
        '<diffuse>0.85 0.85 0.80 1</diffuse></material></visual>\n')
WORLD_FOOTER = """      </link>
    </model>
  </world>
</sdf>
"""


def polygon_area(poly):
    x, y = np.asarray(poly).T
    return 0.5 * float(np.dot(x, np.roll(y, -1)) - np.dot(y, np.roll(x, -1)))


def wall_boxes(poly, free_on_left):
    """(x, y, yaw, length) of a box behind each edge, its face on the edge.

    free_on_left: whether the free space lies left of the edge direction
    (counterclockwise outer boundary, clockwise hole). At convex corners of the
    free space the boxes extend half a thickness so the corner closes; at
    concave ones they stop at the vertex, or they would poke into the free space.
    """
    side = 1.0 if free_on_left else -1.0
    n = len(poly)
    edges = []
    for i in range(n):
        (x0, y0), (x1, y1) = poly[i], poly[(i + 1) % n]
        length = math.hypot(x1 - x0, y1 - y0)
        if length > 1e-3:
            edges.append((x0, y0, (x1 - x0) / length, (y1 - y0) / length, length))

    def convex(a, b):  # the vertex where edge a ends and edge b starts
        return side * (a[2] * b[3] - a[3] * b[2]) > 0

    boxes = []
    for i, edge in enumerate(edges):
        x0, y0, ux, uy, length = edge
        start = WALL_THICKNESS / 2 if convex(edges[i - 1], edge) else 0.0
        end = WALL_THICKNESS / 2 if convex(edge, edges[(i + 1) % len(edges)]) else 0.0
        nx, ny = side * uy, -side * ux  # unit normal pointing away from the free space
        mid = (end - start + length) / 2  # box center along the edge, from (x0, y0)
        boxes.append((x0 + ux * mid + nx * WALL_THICKNESS / 2,
                      y0 + uy * mid + ny * WALL_THICKNESS / 2,
                      math.atan2(uy, ux), length + start + end))
    return boxes


def raster(polys, origin, shape):
    """Fill polygons into a bool grid (row 0 = top, as in the .pgm), cell centers."""
    grid = np.zeros(shape, dtype=np.uint8)
    shift = 4
    pts = []
    for poly in polys:
        x, y = np.asarray(poly, dtype=float).T
        cols = (x - origin[0]) / RESOLUTION - 0.5
        rows = shape[0] - (y - origin[1]) / RESOLUTION - 0.5
        pts.append(np.round(np.stack([cols, rows], axis=1) * 2 ** shift).astype(np.int32))
    cv2.fillPoly(grid, pts, 1, lineType=cv2.LINE_8, shift=shift)
    return grid.astype(bool)


def write_map(path_yaml, pixels, origin, mode='trinary'):
    image = os.path.splitext(os.path.basename(path_yaml))[0] + '.pgm'
    cv2.imwrite(os.path.join(os.path.dirname(path_yaml), image), pixels)
    with open(path_yaml, 'w') as f:
        f.write(f'image: {image}\nmode: {mode}\nresolution: {RESOLUTION:.3f}\n'
                f'origin: [{origin[0]:.3f}, {origin[1]:.3f}, 0]\nnegate: 0\n'
                'occupied_thresh: 0.65\nfree_thresh: 0.196\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('layout')
    parser.add_argument('world_sdf')
    parser.add_argument('map_yaml')
    args = parser.parse_args()

    with open(args.layout) as f:
        layout = yaml.safe_load(f)
    outer = layout['free_space']['outer']
    holes = layout['free_space'].get('holes', [])

    # World: walls behind every edge.
    boxes = wall_boxes(outer, polygon_area(outer) > 0)
    for hole in holes:
        boxes += wall_boxes(hole, polygon_area(hole) < 0)
    xs, ys = np.asarray(outer).T
    world_name = os.path.splitext(os.path.basename(args.world_sdf))[0]
    with open(args.world_sdf, 'w') as f:
        f.write(WORLD_HEADER.format(
            layout=os.path.basename(args.layout), world=world_name,
            description=layout.get('description', ''),
            cx=(xs.min() + xs.max()) / 2, cy=(ys.min() + ys.max()) / 2,
            sx=xs.max() - xs.min() + 10, sy=ys.max() - ys.min() + 10))
        for i, (x, y, yaw, length) in enumerate(boxes):
            f.write(WALL.format(i=i, x=x, y=y, z=WALL_HEIGHT / 2, yaw=yaw, length=length,
                                t=WALL_THICKNESS, h=WALL_HEIGHT))
        f.write(WORLD_FOOTER)

    # Map: free = inside the outer polygon and outside every hole.
    origin = (math.floor(xs.min() - MAP_MARGIN), math.floor(ys.min() - MAP_MARGIN))
    shape = (int(math.ceil((ys.max() + MAP_MARGIN - origin[1]) / RESOLUTION)),
             int(math.ceil((xs.max() + MAP_MARGIN - origin[0]) / RESOLUTION)))
    free = raster([outer], origin, shape) & ~raster(holes, origin, shape) if holes \
        else raster([outer], origin, shape)
    band = int(math.ceil(WALL_BAND / RESOLUTION))
    near = cv2.dilate(free.astype(np.uint8), np.ones((2 * band + 1,) * 2, np.uint8)) > 0
    pixels = np.full(shape, 205, dtype=np.uint8)  # unknown
    pixels[near] = 0
    pixels[free] = 254
    write_map(args.map_yaml, pixels, origin)

    # Keep-out mask (Nav2 KeepoutFilter): occupied where the robot may not go.
    keep = np.full(shape, 254, dtype=np.uint8)
    for x0, y0, x1, y1 in layout.get('keepout', {}).values():
        zone = raster([[[x0, y0], [x1, y0], [x1, y1], [x0, y1]]], origin, shape)
        keep[zone & free] = 0
    write_map(os.path.splitext(args.map_yaml)[0] + '_keepout.yaml', keep, origin)

    print(f'{args.world_sdf}: {len(boxes)} wall boxes; {args.map_yaml}: '
          f'{shape[1]}x{shape[0]} cells, {free.sum() * RESOLUTION ** 2:.0f} m^2 free, '
          f'{(keep == 0).sum() * RESOLUTION ** 2:.0f} m^2 keep-out')


if __name__ == '__main__':
    main()
